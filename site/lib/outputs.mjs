// @ts-check
/*
 * Repository-level outputs: README.md, llms.txt and llms-full.txt.
 * llms.txt follows https://llmstxt.org/: an H1, a blockquote summary,
 * free text, then H2 sections of "- [title](url): note" links.
 */
import { COMPONENT_GROUPS } from "./discovery.mjs";
import { shiftHeadings } from "./markdown.mjs";
import { NAV, navEntryOf } from "./nav.mjs";
import { apiSummary, conventionShortMd, demoListMd, followsMd, installMd, patternStatus, rewriteRepoLinks, sortedPatterns } from "./pages.mjs";
import { resolveSiteLinks, renderMarkdown } from "./templates.mjs";
import { BLOB_URL, RAW_URL, REPO_URL, SITE_URL, escapeMdCell, mdCode, unescapeHtml } from "./util.mjs";

/**
 * @typedef {import("./discovery.mjs").Model} Model
 * @typedef {import("./pages.mjs").Page} Page
 */

export const README_HEADER =
  "<!-- Generated by site/build.mjs from PRINCIPLES.md, css/, examples/ and site/content/. Do not edit; edit those sources and run `node site/build.mjs`. -->";

/** @param {Model} model */
export function generateReadme(model) {
  const link = (/** @type {string} */ md) => resolveSiteLinks(md);

  const principles = model.principles.sections.map((s, i) => `${i + 1}. [${s.title}](site:${s.sitePath})`).join("\n");

  // The API column is the group README's index cell where there is one, else the first word of each API line.
  const row = (/** @type {string} */ group, /** @type {import("./discovery.mjs").Component} */ c) => {
    const api = c.indexApi ? [c.indexApi] : apiSummary(c).map(mdCode);
    if (c.group === "base") api.unshift("none: semantic HTML");
    return `| ${group} | ${escapeMdCell(c.title)} | ${escapeMdCell(api.join(", ") || "not documented yet")} | [${c.title}](site:${c.sitePath}) |`;
  };
  // Available patterns are listed at their level; planned ones only under Patterns.
  const patternRow = (/** @type {string} */ level, /** @type {import("./discovery.mjs").Pattern} */ p) => {
    const api = p.doc ? [...(p.doc.api ? p.doc.api.split("\n").map((l) => l.trim().split(/\s{2,}/)[0]).filter(Boolean) : []), ...p.doc.apiInline] : [];
    return `| ${level} | ${escapeMdCell(p.title)} | ${escapeMdCell(api.map(mdCode).join(", ") || "see the pattern page")} | [${p.title}](site:${p.sitePath}) |`;
  };
  const available = (/** @type {string} */ level) => sortedPatterns(model).filter((p) => p.available && p.level === level);
  // Rows in sidebar order: Base, Layout, Atoms, Molecules, Organisms.
  const rows = [row("Base", model.base), ...model.utilities.map((c) => row("Base (utility)", c))];
  rows.push(...model.layouts.map((c) => row("Layout", c)), ...available("layouts").map((p) => patternRow("Layout", p)));
  for (const { group, title, milestone } of COMPONENT_GROUPS) {
    const items = [...model.components[group].map((c) => row(title, c)), ...available(group).map((p) => patternRow(title, p))];
    if (items.length) rows.push(...items);
    else rows.push(`| ${title} | Coming in ${milestone} | | [components README](${BLOB_URL}css/components/README.md) |`);
  }
  rows.push(...available("tokens").map((p) => patternRow("Tokens", p)));

  const patternRows = sortedPatterns(model).map((p) => `| [${p.title}](site:${p.sitePath}) | ${p.milestone} | ${patternStatus(p)} |`);

  const md = `${README_HEADER}

# domestic-ui

${model.intro}

[Docs](${SITE_URL}) · [llms.txt](site:llms.txt) · [llms-full.txt](site:llms-full.txt)

## Install and use

${installMd(model)}

${conventionShortMd(model)} Theme by overriding semantic \`--dui-*\` tokens ([Tokens](site:tokens/index.html)); primitive tokens are internal.

## Principles

${principles}

## Components

| Level | Name | API | Docs |
| --- | --- | --- | --- |
${rows.join("\n")}

Docs pages also link how other design systems handle the same thing, for comparison only.

## Patterns

Each follows a native element or WAI-ARIA APG pattern where one exists ([Patterns](site:patterns/index.html)). Guides: ${model.guides.map((g) => `[${g.title}](site:${g.sitePath})`).join(", ") || "none yet"}.

| Pattern | Milestone | Status |
| --- | --- | --- |
${patternRows.join("\n")}

## Demos

${demoListMd(model)}${model.demoViews ? `\n\nViews: ${demoViewTitlesMd(model)}; [source per view and app](site:demos.html#views).` : ""}

## Contributing and license

[Contributing](site:contributing.html), [Code of Conduct](${BLOB_URL}CODE_OF_CONDUCT.md), [Security](${BLOB_URL}SECURITY.md), [Changelog](site:changelog.html). \`npm test\` runs every check. [MIT](${BLOB_URL}LICENSE).
`;
  return link(md);
}

/** "Dashboard, Account settings and Orders" @param {Model} model */
const demoViewTitlesMd = (model) => {
  const titles = (model.demoViews?.views ?? []).map((v) => v.title);
  return titles.length > 1 ? `${titles.slice(0, -1).join(", ")} and ${titles.at(-1)}` : titles.join("");
};

/** The header shared by llms.txt and llms-full.txt. @param {Model} model */
function llmsHeader(model) {
  const summary = model.intro.replace(/\s+/g, " ").trim();
  return `# domestic-ui

> ${summary}

Link \`css/domestic.css\` (copy \`css/\` from ${REPO_URL}); semantic HTML needs no classes. ${conventionShortMd(model)} Theme only with semantic \`--dui-*\` tokens; primitives are internal.`;
}

/**
 * @param {Model} model
 * @param {Page[]} pages
 */
export function generateLlms(model, pages) {
  const entry = (/** @type {Page} */ p) => `- [${p.title}](${SITE_URL}${p.path.replace(/\.html$/, ".md")}): ${p.description}`;
  // Available patterns link to their Markdown twin; planned ones are named with their milestone only.
  const patterns = new Map(
    sortedPatterns(model).map((p) => {
      const note = `${p.summary} ${p.standards.length ? `Follows ${followsMd(p)}.` : followsMd(p)}`;
      return [p.sitePath, p.available ? `- [${p.title}](${SITE_URL}${p.sitePath.replace(/\.html$/, ".md")}): Available. ${note}` : `- ${p.title}: ${patternStatus(p)}. ${note}`];
    }),
  );
  const demos = model.demos.map(
    (d) => `- [${d.title}](${REPO_URL}/tree/main/${d.path.replace(/\/$/, "")}): ${resolveSiteLinks(rewriteRepoLinks(d.description.replace(/\s*\n\s*/g, " "), model))}`,
  );
  // One H2 per Docs sidebar entry, in its order.
  const sections = NAV.map((n) => {
    const lines = pages.filter((p) => n.sections.includes(p.section)).map((p) => patterns.get(p.path) ?? entry(p));
    if (n.path === "demos.html") lines.push(...demos);
    if (n.path === "demos.html" && model.demoViews) lines.push(`- [Views](${SITE_URL}demos.md): ${demoViewTitlesMd(model)}, with each app's source file.`);
    return `## ${n.title}\n\n${lines.join("\n")}`;
  });
  return `${llmsHeader(model)}

${sections.join("\n\n")}

## Optional

- [GitHub repository](${REPO_URL}): source, issues and contributing guide
- [PRINCIPLES.md](${RAW_URL}PRINCIPLES.md): the full principles as one Markdown file
- [llms-full.txt](${SITE_URL}llms-full.txt): every reference page in one file
`;
}

/**
 * Every reference page's Markdown twin in one file, headings shifted one
 * level down so the file has a single H1. Pages with `inFull: false` (lists
 * of other pages, guides, Contributing, Changelog) are only in llms.txt.
 * @param {Model} model
 * @param {Page[]} pages
 * @param {Set<string>} twins
 */
export function generateLlmsFull(model, pages, twins) {
  const body = pages.filter((p) => p.inFull !== false).map((p) => {
    const md = renderMarkdown(p, twins, { full: true }).trimEnd();
    const [first, ...rest] = shiftHeadings(md, 1).split("\n");
    return [first, "", `Page: ${SITE_URL}${p.path}`, ...rest].join("\n");
  });
  return `${llmsHeader(model)}\n\n${body.join("\n\n")}\n`;
}

/**
 * A search index for a later in-page search: one record per page with its
 * sidebar entry ("level"), summary and h2/h3 headings. No search UI yet.
 * @param {Page[]} pages
 * @param {Record<string, string>} html rendered HTML by page path
 */
export function searchIndex(pages, html) {
  const records = pages.map((p) => ({
    title: p.title,
    url: p.path,
    level: navEntryOf(p)?.title ?? "",
    summary: p.description,
    headings: [...(html[p.path] ?? "").matchAll(/<h[23] id="[^"]*">([\s\S]*?)<\/h[23]>/g)].map((m) => unescapeHtml(m[1].replace(/<[^>]*>/g, "")).trim()),
  }));
  return `[\n${records.map((r) => JSON.stringify(r)).join(",\n")}\n]\n`;
}
