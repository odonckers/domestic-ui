// @ts-check
/*
 * Repository-level outputs: README.md, llms.txt and llms-full.txt.
 * llms.txt follows https://llmstxt.org/: an H1, a blockquote summary,
 * free text, then H2 sections of "- [title](url): note" links.
 */
import { COMPONENT_GROUPS } from "./discovery.mjs";
import { shiftHeadings, tokenize } from "./markdown.mjs";
import { allComponents, apiSummary, groupMd, installMd, layersMd, rewriteRepoLinks, themingMd } from "./pages.mjs";
import { resolveSiteLinks, renderMarkdown } from "./templates.mjs";
import { BLOB_URL, RAW_URL, REPO_URL, SITE_URL, escapeMdCell, mdCode } from "./util.mjs";

/**
 * @typedef {import("./discovery.mjs").Model} Model
 * @typedef {import("./pages.mjs").Page} Page
 */

export const README_HEADER =
  "<!-- Generated by site/build.mjs from PRINCIPLES.md, css/, examples/ and site/content/. Do not edit; edit those sources and run `node site/build.mjs`. -->";

/**
 * The opening blocks of a principle: the first paragraph, list or table,
 * plus the block after it when it ends with a colon.
 * @param {string} body
 */
function principleSummary(body) {
  const blocks = tokenize(body).filter((b) => b.type !== "heading");
  const first = blocks.findIndex((b) => b.type === "paragraph" || b.type === "list" || b.type === "table");
  if (first < 0) return "";
  const picked = [blocks[first]];
  if (blocks[first].raw.trimEnd().endsWith(":") && blocks[first + 1]) picked.push(blocks[first + 1]);
  return picked.map((b) => b.raw).join("\n\n");
}

/** @param {Model} model */
export function generateReadme(model) {
  const link = (/** @type {string} */ md) => resolveSiteLinks(md);

  const principles = model.principles.sections
    .map((s, i) => `### ${i + 1}. [${s.title}](site:${s.sitePath})\n\n${rewriteRepoLinks(principleSummary(s.body), model)}`)
    .join("\n\n");

  const row = (/** @type {string} */ group, /** @type {import("./discovery.mjs").Component} */ c) => {
    const api = apiSummary(c).map(mdCode);
    if (c.group === "base") api.unshift("none: semantic HTML");
    return `| ${group} | ${escapeMdCell(c.title)} | ${escapeMdCell(api.join(", ") || "not documented yet")} | [${c.title}](site:${c.sitePath}) |`;
  };
  const rows = [row("Base", model.base)];
  for (const { group, title, milestone } of COMPONENT_GROUPS) {
    const items = model.components[group];
    if (items.length) rows.push(...items.map((c) => row(title, c)));
    else rows.push(`| ${title} | Coming in ${milestone} | | [components README](${BLOB_URL}css/components/README.md) |`);
  }
  rows.push(...model.layout.map((c) => row("Layout", c)), ...model.utilities.map((c) => row("Utilities", c)));

  const tokens = model.tokenGroups.map((g) => `- [${g.name}](site:${g.sitePath}): ${g.tokens.map((t) => mdCode(t.name)).join(", ")}`).join("\n");

  const md = `${README_HEADER}

# domestic-ui

${model.intro}

- Docs: <${SITE_URL}>
- Live examples: ${model.examples.map((e) => `[${e.title}](site:${e.path})`).join(", ")}
- For coding agents: [llms.txt](site:llms.txt) and [llms-full.txt](site:llms-full.txt)

## Principles

${model.principles.intro ? `${rewriteRepoLinks(model.principles.intro, model)}\n\n` : ""}${principles}

## Install and use

${installMd(model)}

### Layer order

${layersMd(model)}

### Theming

${themingMd(model)}

## Components

| Group | Name | API | Docs |
| --- | --- | --- | --- |
${rows.join("\n")}

## Tokens

Semantic tokens are the public theming API, in these groups ([Tokens](site:tokens/index.html)):

${tokens}

## Demos

Demo projects in plain HTML/CSS/JS, Angular, React and Astro are planned; links will appear here.

## Contributing

Read [CONTRIBUTING.md](${BLOB_URL}CONTRIBUTING.md), the [Code of Conduct](${BLOB_URL}CODE_OF_CONDUCT.md) and the [security policy](${BLOB_URL}SECURITY.md). \`npm test\` runs every check.

## License

[MIT](${BLOB_URL}LICENSE)
`;
  return link(md);
}

/** The header shared by llms.txt and llms-full.txt. @param {Model} model */
function llmsHeader(model) {
  const summary = model.intro.replace(/\s+/g, " ").trim();
  return `# domestic-ui

> ${summary}

To use it, link \`css/domestic.css\` (copy the \`css/\` folder or clone ${REPO_URL}). Plain semantic HTML then gets the full look with no classes. Each layout primitive, utility and component has one documented class or attribute API, tuned with custom properties, never with modifier classes. Theme only by overriding semantic \`--dui-*\` tokens; primitive tokens are internal and may change.`;
}

/**
 * @param {Model} model
 * @param {Page[]} pages
 */
export function generateLlms(model, pages) {
  const entry = (/** @type {Page} */ p) => `- [${p.title}](${SITE_URL}${p.path.replace(/\.html$/, ".md")}): ${p.description}`;
  const section = (/** @type {Page["section"]} */ s) => pages.filter((p) => p.section === s).map(entry);
  const examples = model.examples.map((e) => `- [${e.title}](${SITE_URL}${e.path}): live example page (HTML)`);
  return `${llmsHeader(model)}

## Principles

${section("principles").join("\n")}

## Tokens

${section("tokens").join("\n")}

## Components

${section("components").join("\n")}

## Examples

${[...section("examples"), ...examples].join("\n")}

## Optional

- [GitHub repository](${REPO_URL}): source, issues and contributing guide
- [PRINCIPLES.md](${RAW_URL}PRINCIPLES.md): the full principles as one Markdown file
- [llms-full.txt](${SITE_URL}llms-full.txt): every docs page in one file
`;
}

/**
 * Every page's Markdown twin in one file, headings shifted one level down
 * so the file has a single H1.
 * @param {Model} model
 * @param {Page[]} pages
 * @param {Set<string>} twins
 */
export function generateLlmsFull(model, pages, twins) {
  const body = pages.map((p) => {
    const md = renderMarkdown(p, twins).trimEnd();
    const [first, ...rest] = shiftHeadings(md, 1).split("\n");
    return [first, "", `Page: ${SITE_URL}${p.path}`, ...rest].join("\n");
  });
  return `${llmsHeader(model)}\n\n${body.join("\n\n")}\n`;
}
